"""Whirl's icon: a speech bubble with a spiral in it (chosen by Dallin, 2026-10-21).

Writes every icon from one geometry on Android's 108-unit adaptive-icon grid (art inside the 66-unit safe circle):
  app/src/main/res/drawable/ic_launcher_foreground.xml   bubble and spiral, also the monochrome (themed) layer
  app/src/main/res/drawable/ic_launcher_background.xml   deep-ocean gradient
  core/notifications/src/main/res/drawable/ic_stat_whirl.xml   status bar icon (heavier lines, fewer turns)
  tools/store-graphics/icon.html, feature.html           rendered to PNG by render.mjs (see README.md)

    python3 tools/store-graphics/make_icon.py   # from the repository root
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
C = 54.0
LIGHT, DARK, ACCENT = '#0C5962', '#071E2B', '#49E2D0'
CENTRE = (C - 1, C - 2)


def num(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def spiral(cx, cy, r0, r1, turns, start_deg, n=120):
    """Archimedean spiral from radius r0 to r1 as a polyline (angles grow clockwise, y down)."""
    pts = []
    for i in range(n + 1):
        t = i / n
        a = math.radians(start_deg) + t * turns * 2 * math.pi
        r = r0 + (r1 - r0) * t
        pts.append(f'{num(cx + r * math.cos(a))},{num(cy + r * math.sin(a))}')
    return 'M' + ' L'.join(pts)


def bubble(cx, cy, r, tail_deg=45, gap_deg=18, tail_len=8):
    """A circle left open where the tail leaves (lower right), closed through the tail's tip."""
    a1, a2 = math.radians(tail_deg - gap_deg / 2), math.radians(tail_deg + gap_deg / 2)
    ta = math.radians(tail_deg - 4)
    p1 = (cx + r * math.cos(a1), cy + r * math.sin(a1))
    p2 = (cx + r * math.cos(a2), cy + r * math.sin(a2))
    tip = (cx + (r + tail_len) * math.cos(ta), cy + (r + tail_len) * math.sin(ta))
    return (f'M{num(p2[0])},{num(p2[1])} A{num(r)},{num(r)} 0 1 1 {num(p1[0])},{num(p1[1])} '
            f'L{num(tip[0])},{num(tip[1])} Z')


# The launcher icon: bubble 3.5, spiral 2.75, 2.25 turns starting at 30 degrees.
BUBBLE, BUBBLE_W = bubble(*CENTRE, 21), 3.5
SPIRAL, SPIRAL_W = spiral(*CENTRE, 1, 14, 2.25, 30), 2.75
# The status bar icon is drawn at 24 dp: heavier lines and fewer turns so it survives that size.
STAT_BUBBLE, STAT_BUBBLE_W = BUBBLE, 6
STAT_SPIRAL, STAT_SPIRAL_W = spiral(*CENTRE, 1.5, 12.5, 1.6, 30), 5.5

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/store-graphics/make_icon.py; edit that instead. -->\n'


def vector_path(d, width, colour='#FFFFFFFF', indent='    '):
    attrs = ['android:fillColor="#00000000"', f'android:strokeColor="{colour}"', f'android:strokeWidth="{num(width)}"',
             'android:strokeLineCap="round"', 'android:strokeLineJoin="round"', f'android:pathData="{d}"']
    return f'{indent}<path\n' + '\n'.join(f'{indent}    {a}' for a in attrs) + ' />\n'


INK = f'#FF{ACCENT[1:]}'


def write(rel, text):
    path = ROOT / rel
    path.write_text(text)
    print('wrote', rel)


def main():
    write('app/src/main/res/drawable/ic_launcher_foreground.xml', HEADER +
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    android:width="108dp"\n    android:height="108dp"\n'
          '    android:viewportWidth="108"\n    android:viewportHeight="108">\n' +
          vector_path(BUBBLE, BUBBLE_W, INK) + vector_path(SPIRAL, SPIRAL_W, INK) + '</vector>\n')
    write('app/src/main/res/drawable/ic_launcher_background.xml', HEADER +
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp"\n    android:height="108dp"\n'
          '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
          '    <path android:pathData="M0,0 H108 V108 H0 Z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          '            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">\n'
          f'                <item android:offset="0" android:color="#FF{LIGHT[1:]}" />\n'
          f'                <item android:offset="1" android:color="#FF{DARK[1:]}" />\n'
          '            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n')
    write('app/src/main/res/values/splash.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          '    <!-- Deep-ocean backdrop matching the launcher icon (tools/store-graphics/make_icon.py). -->\n'
          '    <color name="splash_background">#0B3C47</color>\n</resources>\n')
    # 24 dp status bar icon: the 108 grid scaled so the bubble (and its tail) fills it. Only alpha is used.
    scale = 24 / 62
    write('core/notifications/src/main/res/drawable/ic_stat_whirl.xml', HEADER +
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    android:width="24dp"\n    android:height="24dp"\n'
          '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
          f'    <group\n        android:scaleX="{num(scale)}"\n        android:scaleY="{num(scale)}"\n'
          f'        android:translateX="{num(12 - (CENTRE[0] + 2) * scale)}"\n'
          f'        android:translateY="{num(12 - (CENTRE[1] + 2) * scale)}">\n' +
          vector_path(STAT_BUBBLE, STAT_BUBBLE_W, indent='        ') +
          vector_path(STAT_SPIRAL, STAT_SPIRAL_W, indent='        ') +
          '    </group>\n</vector>\n')
    svg_art = (f'<path d="{BUBBLE}" fill="none" stroke="{ACCENT}" stroke-width="{BUBBLE_W}" stroke-linecap="round" stroke-linejoin="round"/>'
               f'<path d="{SPIRAL}" fill="none" stroke="{ACCENT}" stroke-width="{SPIRAL_W}" stroke-linecap="round"/>')
    gradient = (f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{LIGHT}"/>'
                f'<stop offset="1" stop-color="{DARK}"/></linearGradient></defs>')
    # Play's icon is full bleed (Play applies its own mask and corner radius): a slightly wider window than the
    # launcher's 72 units keeps the tail clear of the rounded corners.
    write('tools/store-graphics/icon.html',
          '<!doctype html><html><body style="margin:0">\n'
          f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="13 13 82 82">{gradient}'
          f'<rect width="108" height="108" fill="url(#g)"/>{svg_art}</svg></body></html>\n')
    write('tools/store-graphics/feature.html',
          '<!doctype html><html><head><style>\n'
          f'body{{margin:0;width:1024px;height:500px;background:linear-gradient(135deg,{LIGHT},{DARK});'
          "font-family:'Roboto','Noto Sans',system-ui,sans-serif;color:#fff;display:flex;align-items:center;gap:56px;"
          'padding:0 96px;box-sizing:border-box}\n'
          'h1{font-size:120px;margin:0;font-weight:500;letter-spacing:-2px}\n'
          'p{font-size:38px;margin:8px 0 0;opacity:.9}\n'
          '</style></head><body>\n'
          f'<svg width="240" height="240" viewBox="27 26 52 52">{svg_art}</svg>\n'
          '<div><h1>Whirl</h1><p>A forum reader for Android</p></div>\n'
          '</body></html>\n')


if __name__ == '__main__':
    main()
